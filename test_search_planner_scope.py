from agents.search_planner import (
    SearchPlanner,
)

from config import settings

from models.factory import (
    ChatModelFactory,
)


print()
print("SEARCH PLANNER SCOPE TEST")
print("=========================")


#
# -------------------------------------------------
# Test inputs.
#
# Both tests use exactly the same topic, question,
# purpose, instructions, and model.
#
# The only intentional difference is persistent
# research scope.
# -------------------------------------------------
#

topic = (
    "The effect of Bitcoin mining "
    "on energy systems"
)

question = (
    "How does Bitcoin mining affect "
    "electricity markets?"
)

scope = (
    "Focus specifically on electricity pricing, "
    "grid incentives, and renewable-energy "
    "investment."
)


#
# -------------------------------------------------
# Create the real researcher model.
#
# SearchPlanner is part of the research/discovery
# path, so use the configured researcher model.
# -------------------------------------------------
#

print()
print("MODEL")
print("-----")

print(
    f"Provider: "
    f"{settings.researcher_model.provider}"
)

print(
    f"Model:    "
    f"{settings.researcher_model.model_name}"
)

print(
    f"Base URL: "
    f"{settings.researcher_model.base_url}"
)


model = ChatModelFactory.create(
    settings.researcher_model
)

search_planner = SearchPlanner(
    model=model
)


#
# -------------------------------------------------
# TEST 1
#
# No persistent research scope.
#
# This establishes the baseline search behaviour
# for the topic/question.
# -------------------------------------------------
#

print()
print("TEST 1 - NO PERSISTENT SCOPE")
print("============================")

print()
print(f"Topic:    {topic}")
print(f"Question: {question}")
print("Scope:    None")

print()
print("Calling Qwen...")


baseline_plan = search_planner.create_plan(
    topic=topic,
    question=question,
    scope=None,
    purpose="initial",
    instructions=None,
    existing_evidence_context=None,
)


print()
print("BASELINE SEARCH QUERIES")
print("-----------------------")


for index, search_query in enumerate(
    baseline_plan.queries,
    start=1,
):

    print()
    print(
        f"Query {index}: "
        f"{search_query.query}"
    )

    print(
        f"Rationale: "
        f"{search_query.rationale}"
    )


#
# -------------------------------------------------
# TEST 2
#
# Same research problem, but now with a persistent
# scope.
#
# The SearchPlanner should keep its queries inside
# that durable research boundary.
# -------------------------------------------------
#

print()
print()
print("TEST 2 - PERSISTENT SCOPE")
print("=========================")

print()
print(f"Topic:    {topic}")
print(f"Question: {question}")
print(f"Scope:    {scope}")

print()
print("Calling Qwen...")


scoped_plan = search_planner.create_plan(
    topic=topic,
    question=question,
    scope=scope,
    purpose="initial",
    instructions=None,
    existing_evidence_context=None,
)


print()
print("SCOPED SEARCH QUERIES")
print("---------------------")


for index, search_query in enumerate(
    scoped_plan.queries,
    start=1,
):

    print()
    print(
        f"Query {index}: "
        f"{search_query.query}"
    )

    print(
        f"Rationale: "
        f"{search_query.rationale}"
    )


#
# -------------------------------------------------
# Structural validation.
#
# We deliberately do NOT assert exact query text.
#
# Query wording is generated by the model and is
# therefore nondeterministic. This test checks the
# structured-output contract automatically and
# leaves semantic scope adherence visible for
# inspection.
# -------------------------------------------------
#

assert baseline_plan.queries, (
    "Baseline SearchPlanner returned "
    "no search queries."
)

assert scoped_plan.queries, (
    "Scoped SearchPlanner returned "
    "no search queries."
)

assert len(baseline_plan.queries) <= 3, (
    "Baseline SearchPlanner returned "
    "more than three queries."
)

assert len(scoped_plan.queries) <= 3, (
    "Scoped SearchPlanner returned "
    "more than three queries."
)


for search_query in baseline_plan.queries:

    assert search_query.query.strip()

    assert search_query.rationale.strip()


for search_query in scoped_plan.queries:

    assert search_query.query.strip()

    assert search_query.rationale.strip()


print()
print()
print("STRUCTURAL VALIDATION")
print("=====================")

print(
    "Baseline plan returned queries: PASSED"
)

print(
    "Scoped plan returned queries: PASSED"
)

print(
    "Maximum three queries: PASSED"
)

print(
    "SearchQuery structured output: PASSED"
)


#
# -------------------------------------------------
# Comparison.
#
# This is informational rather than a hard
# assertion because an LLM could legitimately
# produce some identical queries in both plans.
# -------------------------------------------------
#

baseline_queries = {
    item.query.strip().lower()
    for item in baseline_plan.queries
}

scoped_queries = {
    item.query.strip().lower()
    for item in scoped_plan.queries
}


print()
print("PLAN COMPARISON")
print("===============")


if baseline_queries == scoped_queries:

    print(
        "WARNING: The scoped and unscoped "
        "query sets are identical."
    )

    print(
        "Inspect the generated rationales and "
        "consider whether the persistent scope "
        "is influencing planning strongly enough."
    )

else:

    print(
        "Scoped and unscoped query sets differ."
    )


print()
print("=========================")
print("TEST COMPLETE")
print("=========================")

print(
    "Inspect the scoped queries above and verify "
    "that they remain focused on electricity "
    "pricing, grid incentives, and "
    "renewable-energy investment."
)